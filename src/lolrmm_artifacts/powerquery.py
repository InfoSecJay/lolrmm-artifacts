# --- rendering ---------------------------------------------------------------------


def _quote(value: str) -> str:
    """PowerQuery string literal: single-quoted unless the value holds a single quote."""
    if "'" not in value:
        return f"'{value}'"
    return '"' + value.replace('"', '\\"') + '"'


def build_query(spec: RuleSpec, values: list[str]) -> str:
    body = ",\n".join(f"    {_quote(v)}" for v in values)
    return f"{spec.head}{body}\n{spec.tail}"


def _block(text: str, indent: str = "  ") -> list[str]:
    return [f"{indent}{line}" if line else "" for line in text.rstrip("\n").split("\n")]


def _yaml_list(key: str, items: list[str], indent: str = "") -> list[str]:
    if not items:
        return [f"{indent}{key}: []"]
    quoted = [json.dumps(item, ensure_ascii=False) for item in items]
    return [f"{indent}{key}:"] + [f"{indent}  - {q}" for q in quoted]


def render(spec: RuleSpec, query: str, generated: dict, modified: str) -> str:
    """Sigma-shaped YAML with the PowerQuery as a literal block. Hand-rendered so
    the layout (comment header, block scalar, key order) is stable for git diffs."""
    lines: list[str] = [
        "# Generated by `lolrmm refresh` from the LOLRMM corpus. Do not edit by hand;",
        "# the indicator list is rewritten on every refresh so it tracks upstream.",
        f"title: {spec.title}",
        f"id: {spec.id}",
        "status: experimental",
        "description: |",
        *_block(spec.description),
        f"author: {AUTHOR}",
        f"date: {RULE_DATE}",
        f"modified: {modified}",
        "references:",
        *[f"  - {r}" for r in REFERENCES],
        "tags:",
        *[f"  - {t}" for t in spec.tags],
        "logsource:",
        "  product: sentinelone",
        "  service: powerquery",
        f"  category: {spec.category}",
        "generated:",
    ]
    for key, val in generated.items():
        if isinstance(val, list):
            lines += _yaml_list(key, val, indent="  ")
        else:
            lines.append(f"  {key}: {val}")
    lines += [
        "query: |",
        *_block(query),
        "falsepositives:",
        *[f"  - {fp}" for fp in spec.falsepositives],
        f"level: {spec.level}",
    ]
    return "\n".join(lines) + "\n"


def _carry_modified(previous_text: str | None, query: str, today: str) -> str:
    """Keep the previous `modified` date unless the query text changed, so a
    daily refresh with no new indicators leaves the file byte-identical."""
    if not previous_text:
        return today
    try:
        prev = yaml.safe_load(previous_text)
    except yaml.YAMLError:
        return today
    if isinstance(prev, dict) and prev.get("modified"):
        if str(prev.get("query", "")).rstrip() == query.rstrip():
            return str(prev["modified"])
    return today


def build(spec: RuleSpec, tools: list[Tool]) -> tuple[str, dict]:
    """Return (query text, `generated:` metadata) for one rule."""
    values, meta = spec.collect(tools)
    generated = {"source": meta.pop("source"), "indicators": len(values), "tools": len(tools)}
    generated.update(meta)
    return build_query(spec, values), generated


def write_rules(tools: list[Tool], out_dir: Path, today: str | None = None) -> dict[str, Path]:
    today = today or date.today().isoformat()
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for spec in RULES:
        query, generated = build(spec, tools)
        path = out_dir / spec.filename
        previous = path.read_text(encoding="utf-8") if path.exists() else None
        text = render(spec, query, generated, _carry_modified(previous, query, today))
        # LF on every platform so a local run and the Linux CI run produce the same bytes.
        path.write_text(text, encoding="utf-8", newline="\n")
        paths[spec.key] = path
    return paths
