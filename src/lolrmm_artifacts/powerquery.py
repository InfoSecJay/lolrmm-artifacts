"""SentinelOne PowerQuery hunting rules generated from the LOLRMM corpus.

Two rules, one YAML file each, rewritten on every `lolrmm refresh` so the
indicator lists never drift from upstream:

- process: `src.process.displayName` against every application alias
  (the same set as applications.csv / application_name_lower).
- url:     `url.address` against every Network domain artifact, normalised
  into literal substrings that PowerQuery `contains` can actually match.

The file layout is Sigma-shaped (title/id/description/tags/logsource/
falsepositives/level) so the query travels with its metadata; the detection
itself is a verbatim PowerQuery under `query:`.
"""

